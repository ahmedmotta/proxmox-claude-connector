#!/usr/bin/env python3
"""Build the theme files Proxmox loads from /pwt/themes/.

    python3 gui/theme/build.py                       # assemble dist/ from src/
    python3 gui/theme/build.py --crisp theme-crisp-all.css   # also regenerate src/font-overrides.css

Output (gui/theme/dist/), everything gui/install-gui.sh puts on a node:
    theme-pcc-dark.css   Proxmox's own dark theme (imported from the server) + the brand on top
    theme-pcc-light.css  the stock light look + the brand on top
    claude-theme.js      header, theme switcher, charts (served from /pve2/js/)
    pcc-*.woff2, pcc-logo.png, pcc-fonts-OFL.txt
    SHA256SUMS           checked by the installer before anything is copied
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC, DIST = HERE / "src", HERE / "dist"

LATIN = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,"
    "U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
)
LATIN_EXT = (
    "U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,"
    "U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF"
)
FONTS = [
    ("PCC Inter", "pcc-inter-latin.woff2", "100 900", LATIN),
    ("PCC Inter", "pcc-inter-latin-ext.woff2", "100 900", LATIN_EXT),
    ("PCC Grotesk", "pcc-grotesk-latin.woff2", "300 700", LATIN),
    ("PCC Grotesk", "pcc-grotesk-latin-ext.woff2", "300 700", LATIN_EXT),
    ("PCC Mono", "pcc-mono-latin.woff2", "100 800", LATIN),
]
# Inter is about 5% wider than Helvetica/Arial at the same size: scale every size so text keeps
# its original width and no ExtJS layout (columns, labels, buttons) gets tighter.
INTER_SCALE = 0.962


def font_faces() -> str:
    out = []
    for family, file, weight, rng in FONTS:
        out.append(
            f'@font-face {{\n    font-family: "{family}";\n    src: url("{file}") format("woff2");\n'
            f"    font-weight: {weight};\n    font-style: normal;\n    font-display: swap;\n"
            f"    unicode-range: {rng};\n}}"
        )
    return "\n".join(out) + "\n"


def gen_font_overrides(crisp_css: Path) -> str:
    """Every ExtJS rule that sets a text font gets Inter at a width-matched size."""
    css = re.sub(r"/\*.*?\*/", "", crisp_css.read_text(encoding="utf-8"), flags=re.S)
    by_size: dict[str, set[str]] = {}
    for selectors, body in re.findall(r"([^{}@]+)\{([^{}]*)\}", css):
        decl = re.search(r"font(?:-family)?\s*:\s*([^;]+)", body)
        if not decl or not re.search(r"helvetica|arial|verdana", decl.group(1), re.I):
            continue
        size = (
            re.search(r"(\d+(?:\.\d+)?)px", re.search(r"font\s*:\s*([^;]+)", body).group(1))
            if re.search(r"font\s*:", body)
            else re.search(r"font-size\s*:\s*(\d+(?:\.\d+)?)px", body)
        )
        key = f"{float(size.group(1)) * INTER_SCALE:.2f}px" if size else ""
        for sel in selectors.split(","):
            sel = sel.strip()
            if sel and "::" not in sel and ":after" not in sel and ":before" not in sel:
                by_size.setdefault(key, set()).add(sel)
    lines = ["/* Generated by build.py from the ExtJS crisp theme: text fonts only, icon fonts untouched. */"]
    for size in sorted(by_size, key=lambda s: (s == "", s)):
        sels = ",\n".join(f":root {s}" for s in sorted(by_size[size]))
        body = "font-family: var(--pcc-font);" + (f" font-size: {size};" if size else "")
        lines.append(f"{sels} {{\n    {body}\n}}")
    return "\n".join(lines) + "\n"


def build() -> None:
    DIST.mkdir(exist_ok=True)
    for old in DIST.iterdir():  # nothing stale may ship
        old.unlink()
    faces = font_faces()
    overrides = (SRC / "font-overrides.css").read_text(encoding="utf-8")
    components = (SRC / "components.css").read_text(encoding="utf-8")
    components += (SRC / "console.css").read_text(encoding="utf-8")  # the app shell and cards, last
    banner = (
        "/* Proxmox Claude Connector theme - https://github.com/ahmedmotta/proxmox-claude-connector\n"
        " * Generated by gui/theme/build.py; edit src/ and rebuild.\n"
        " * MIT licensed (fonts: OFL-1.1). */\n"
    )
    dark = (
        banner
        + '@import url("theme-proxmox-dark.css");\n'  # Proxmox's own dark theme, loaded from the server
        + faces
        + (SRC / "tokens-dark.css").read_text(encoding="utf-8")
        + overrides
        + components
    )
    light = banner + faces + (SRC / "tokens-light.css").read_text(encoding="utf-8") + overrides + components
    builds = {}
    for name, css in (("pcc-dark", dark), ("pcc-light", light)):
        # claude-theme.js compares this id with the one it expects, to catch a browser's stale copy
        builds[name] = hashlib.sha256(css.encode("utf-8")).hexdigest()[:12]
        css += f':root {{\n    --pcc-build: "{builds[name]}";\n}}\n'
        (DIST / f"theme-{name}.css").write_text(css, encoding="utf-8")
    for f in sorted((HERE / "fonts").glob("*.woff2")):
        shutil.copy(f, DIST / f.name)
    shutil.copy(HERE / "fonts/LICENSE-OFL.txt", DIST / "pcc-fonts-OFL.txt")
    shutil.copy(HERE / "brand/logo.png", DIST / "pcc-logo.png")
    script = (HERE / "claude-theme.js").read_text(encoding="utf-8")
    assert "'__THEME_BUILDS__'" in script
    script = script.replace("'__THEME_BUILDS__'", json.dumps(builds, sort_keys=True))
    (DIST / "claude-theme.js").write_text(script, encoding="utf-8")
    sums = "".join(
        f"{hashlib.sha256(f.read_bytes()).hexdigest()}  {f.name}\n" for f in sorted(DIST.iterdir())
    )
    (DIST / "SHA256SUMS").write_text(sums, encoding="utf-8")
    print(f"built {DIST} ({len(dark) // 1024} KB dark, {len(light) // 1024} KB light)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--crisp", type=Path, help="ExtJS theme-crisp CSS to regenerate the font overrides from"
    )
    args = parser.parse_args()
    if args.crisp:
        (SRC / "font-overrides.css").write_text(gen_font_overrides(args.crisp), encoding="utf-8")
    build()
